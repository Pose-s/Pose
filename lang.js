// Funzione helper per ottenere una traduzione nei file JavaScript
export function t(key) {
  const currentLang = localStorage.getItem('app_lang') || 'it';
  const dict = translations[currentLang] || translations.it;
  return dict[key] || key;
}

// Applica le traduzioni a tutti gli elementi HTML con [data-i18n]
export function applyLanguage(lang = null) {
  const currentLang = lang || localStorage.getItem('app_lang') || 'it';
  const dict = translations[currentLang] || translations.it;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  document.documentElement.lang = currentLang;
}

// Si avvia automaticamente appena il DOM è pronto
if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', () => {
    applyLanguage();
  });
}